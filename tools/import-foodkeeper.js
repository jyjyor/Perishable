#!/usr/bin/env node
// Turns tools/data/foodkeeper.json (USDA FoodKeeper, unmodified) into the
// compact fallback table in index.html, between the FOODKEEPER markers.
// Re-runnable; never hand-edit its output -- change this script and run it
// again. The rule is the one recorded in CLAUDE.md:
//   - refrigerator, counted from purchase: DOP_Refrigerate, else Refrigerate
//   - foods usually kept out of the fridge (PANTRY_KEPT): DOP_Pantry, else
//     Pantry; "When Ripe" falls back to the refrigerator number
//   - upper end of a range; days x1, weeks x7, months x30, years x365
//   - a refrigerator number FoodKeeper says "applies to ripe fruit" counts
//     from ripeness, not purchase: kept as 'ripe', so the app asks for a
//     date with the hint "about N days after it ripens"
//   - no number, but the refrigerator guidance is the package date: kept,
//     with no days, so the app asks for the printed date
//   - no number at all: left out, so the app treats it as no match
//
// Run: node tools/import-foodkeeper.js

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const SRC = path.join(__dirname, 'data', 'foodkeeper.json');
const HTML = path.join(ROOT, 'index.html');
const BEGIN = '/* BEGIN FOODKEEPER -- generated by tools/import-foodkeeper.js from tools/data/foodkeeper.json; do not edit by hand */';
const END = '/* END FOODKEEPER */';

const PANTRY_KEPT = new Set([251, 297, 422, 294, 285, 306, 303, 596, 298, 250, 195, 460, 461, 574, 449]);
// Hand-kept aliases for obvious misses: what people call these at the
// store when FoodKeeper's own name and keywords don't say it. Kept short;
// each is the same food (or the same species under a generic entry), and
// they bypass the keyword filters below.
const HAND_ALIASES = new Map([
  [263, ['kiwi', 'kiwis']],                          // Kiwi fruit
  [256, ['mandarin', 'mandarins']],                  // Citrus fruit (... tangerines, clementines)
  [73, ['ground pork']],                             // Pork (ground)
  [115, ['ground chicken']],                         // Ground turkey or chicken
  [67, ['pork tenderloin']],                         // Pork (tenderloin)
  [514, ['deli turkey', 'sliced turkey']],           // Turkey (pre-packaged, luncheon/deli meat)
  [515, ['deli ham', 'sliced ham']],                 // Ham (pre-packaged, luncheon/deli meat)
  [302, ['summer squash', 'yellow squash']],         // Squash (summer and zucchini)
  [195, ['pita', 'naan']]                            // Commercial bread products (... flat breads ...)
]);

// Hand-kept exceptions to the ripeness reading, with the reason. A store
// pineapple is already as ripe as it gets, so its number counts from
// purchase like any other.
const FROM_PURCHASE = new Map([[267, 'pineapple: sold ripe; does not ripen further']]);
const MULT = { Day: 1, Days: 1, Week: 7, Weeks: 7, Month: 30, Months: 30, Year: 365, Years: 365 };

// Words that only describe a food's state, cut or packaging. A keyword made
// of one of these alone would match half the dataset, so it never becomes
// an alias. Single-word keywords shared by more than MAX_SHARED items are
// dropped for the same reason; the item's own name still matches. A keyword
// that is another item's own name ("apple" on Apple juice, "almond" on
// Almond milk) is dropped too, and so is a one-word keyword that is only part
// of this item's longer name ("potato" on Potato salad): "apple juice" must
// never resolve to apples, nor "apple" to apple juice. A one-word keyword is
// kept only when the item's subtitle names it as a member ("Cheese (hard
// such as cheddar, swiss...)" -> cheddar, swiss) and it does not begin
// another item's name ("corn" on Tortillas would steal Corn on the cob);
// the rest are qualifiers ("heavy", "live", "tub") or another food.
const GENERIC = new Set(('fresh frozen cooked uncooked raw whole half halves sliced slice cut chopped dry dried ' +
  'commercial commercially homemade store bought pack packaged pre-packaged refrigerated can canned jar ' +
  'cube cubes round hot smoked uncured cured pasteurized ultra-pasteurized squeezed shell bone bone-in ' +
  'boneless skinless whipped substitute cook-before-eating roll rolls rolled leg legs loin rib ribs shank ' +
  'shoulder tenderloin chops stew roast juice juices salad leftovers leftover meat meats poultry fish ' +
  'seafood fruit fruits vegetable vegetables nut nuts plain flavored flavor regular other etc green red ' +
  'white yellow black brown dark light sweet hard soft mix mixes product products food foods opened ' +
  'unopened package leaf leaves shredded grated slices processed ultra stuffed spring bagged greens ' +
  'fermented rotisserie baby heavy liquid sweetened whipping tub domestic wild young all cold natural ' +
  'plastic salted prepared summer winter traditional ultrapasteurized piece rump butt gutted precooked ' +
  'jarred sprout wax king snow').split(/\s+/));
// Multi-word keywords that describe a preparation, not a food.
const GENERIC_PHRASE = new Set(['fresh squeezed', 'without meat', 'no shell', 'commercially produced',
  'luncheon meat', 'deli meat', 'processed slices']);
const MAX_SHARED = 4;

function rowsOf(sheet) {
  return sheet.data.map(r => Object.assign({}, ...r));
}

function range(r, col) {
  const mn = r[col + '_Min'], mx = r[col + '_Max'], metric = r[col + '_Metric'];
  const hi = typeof mx === 'number' ? mx : (typeof mn === 'number' ? mn : null);
  if (hi == null || !MULT[metric]) return null;
  return Math.round(hi * MULT[metric]);
}

function valueOf(r) {
  const id = r.ID;
  const order = (PANTRY_KEPT.has(id) ? [['DOP_Pantry', 'P'], ['Pantry', 'P']] : [])
    .concat([['DOP_Refrigerate', 'R'], ['Refrigerate', 'R']]);
  for (const [col, store] of order) {
    const days = range(r, col);
    if (days != null){
      if (col === 'Refrigerate' && /applies to ripe/i.test(r.Refrigerate_tips || '') && !FROM_PURCHASE.has(id)) return { days, store: 'ripe' };
      return { days, store };
    }
  }
  if (['DOP_Refrigerate', 'Refrigerate'].some(c => r[c + '_Metric'] === 'Package use-by date')) {
    return { days: null, store: 'pkg' };
  }
  return null;
}

function norm(s) {
  return String(s).toLowerCase().replace(/&/g, ' and ').replace(/[^a-z0-9 -]+/g, ' ').replace(/\s+/g, ' ').trim();
}

// Same normalisation as normName() in index.html: lowercase, punctuation
// out, each word singular.
function single(w) {
  if (/ies$/.test(w) && w.length > 4) return w.slice(0, -3) + 'y';
  if (/oes$/.test(w)) return w.slice(0, -2);
  if (/(ch|sh|x|ss)es$/.test(w)) return w.slice(0, -2);
  if (/s$/.test(w) && !/ss$/.test(w) && w.length > 3) return w.slice(0, -1);
  return w;
}
function key(s) {
  return norm(s).split(' ').filter(Boolean).map(single).join(' ');
}
// "Carrots, parsnips" -> ["carrot", "parsnip"]; "Pitaya/dragon fruit" -> two.
function segments(name) {
  return String(name).split(/[,/]| or /).map(key).filter(Boolean);
}

function main() {
  const data = JSON.parse(fs.readFileSync(SRC, 'utf8'));
  const sheets = Object.fromEntries(data.sheets.map(s => [s.name, s]));
  const cats = new Map(rowsOf(sheets.Category).map(c => [c.ID, c.Subcategory_Name ? `${c.Category_Name} / ${c.Subcategory_Name}` : c.Category_Name]));
  const products = rowsOf(sheets.Product).map(r => ({ ...r, ID: Math.round(r.ID), Category_ID: Math.round(r.Category_ID) }));

  const kept = [];
  for (const r of products) {
    const v = valueOf(r);
    if (v) kept.push({ r, v });
  }

  // How many kept items share each single-word keyword.
  const shared = new Map();
  for (const { r } of kept) {
    const words = new Set(String(r.Keywords || '').split(',').map(norm).filter(k => k && !k.includes(' ')));
    for (const w of words) shared.set(w, (shared.get(w) || 0) + 1);
  }

  // Every kept item's own name segments, to stop one item's keyword
  // claiming another item's name, and the first word of each.
  const owners = new Map(), heads = new Map();
  const claim = (m, k, id) => { if (!m.has(k)) m.set(k, new Set()); m.get(k).add(id); };
  for (const { r } of kept) for (const seg of segments(r.Name)) {
    claim(owners, seg, r.ID);
    claim(heads, seg.split(' ')[0], r.ID);
  }
  const elsewhere = (m, k, id) => m.has(k) && [...m.get(k)].some(o => o !== id);

  const catNames = [];
  const catIndex = name => {
    let i = catNames.indexOf(name);
    if (i < 0) { catNames.push(name); i = catNames.length - 1; }
    return i;
  };

  let dropped = 0;
  const rows = kept.map(({ r, v }) => {
    const name = r.Name_subtitle ? `${r.Name.trim()} (${r.Name_subtitle.trim()})` : r.Name.trim();
    const own = segments(r.Name);
    const members = new Set(String(r.Name_subtitle || '').replace(/such as|etc\.?/gi, ',')
      .split(/[,;()/]| or | and /).map(key).filter(Boolean));
    const inside = k => own.some(seg => seg !== k && (' ' + seg + ' ').includes(' ' + k + ' '));
    const aliases = [];
    for (const raw of String(r.Keywords || '').split(',').map(norm)) {
      const k = key(raw);
      if (!k || own.includes(k) || aliases.includes(k)) continue;
      const oneWord = !k.includes(' ');
      if ((oneWord && (GENERIC.has(raw) || GENERIC.has(k) || (shared.get(raw) || 0) > MAX_SHARED ||
                       !members.has(k) || elsewhere(heads, k, r.ID))) ||
          GENERIC_PHRASE.has(raw) || elsewhere(owners, k, r.ID) || inside(k)) { dropped++; continue; }
      aliases.push(k);
    }
    for (const a of HAND_ALIASES.get(r.ID) || []) if (!aliases.includes(key(a))) aliases.push(key(a));
    return [r.ID, name, aliases.join('|'), v.days, v.store, catIndex(cats.get(r.Category_ID) || 'Unknown')];
  }).sort((a, b) => a[0] - b[0]);

  const body =
    `// [FoodKeeper id, name, aliases (|-separated, normalised, from its keywords), days or null,\n` +
    `//  storage column (R refrigerator, P pantry, ripe refrigerator counted from\n` +
    `//  ripeness, pkg package date), category index]\n` +
    `const FK_CATEGORIES = ${JSON.stringify(catNames)};\n` +
    `const FK_TABLE = [\n` + rows.map(r => JSON.stringify(r)).join(',\n') + `\n];`;
  const block = `${BEGIN}\n${body}\n${END}`;

  const html = fs.readFileSync(HTML, 'utf8');
  const a = html.indexOf(BEGIN), b = html.indexOf(END);
  if (a < 0 || b < 0 || b < a) throw new Error('FOODKEEPER markers not found in index.html');
  fs.writeFileSync(HTML, html.slice(0, a) + block + html.slice(b + END.length));

  const counts = { R: 0, P: 0, ripe: 0, pkg: 0 };
  rows.forEach(r => counts[r[4]]++);
  console.log(`${rows.length} items written (refrigerator ${counts.R}, pantry ${counts.P}, from ripeness ${counts.ripe}, package date ${counts.pkg}); ` +
    `${products.length - rows.length} left out with no value; ${dropped} generic keywords dropped; ` +
    `${[...HAND_ALIASES.values()].flat().length} hand-kept aliases; ` +
    `table ${(Buffer.byteLength(block) / 1024).toFixed(1)} KB.`);
}

main();
